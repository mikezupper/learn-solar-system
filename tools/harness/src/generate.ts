const HEADER = (title: string) =>
  `# ${title}\n\nGenerated by \`pnpm gen-docs\` from the code. Do not edit by hand; \`pnpm gen-docs --check\` fails if this file drifts.\n`

export interface WorkspacePackage {
  readonly name: string
  readonly path: string
  readonly dependencies: ReadonlyArray<string>
  readonly layers: ReadonlyArray<{ readonly layer: string; readonly files: number }>
}

export const renderWorkspace = (packages: ReadonlyArray<WorkspacePackage>): string =>
  [
    HEADER("Workspace"),
    "| Package | Path | Layers (source files) | Runtime dependencies |",
    "|---|---|---|---|",
    ...packages.map(
      ({ name, path, layers, dependencies }) =>
        `| \`${name}\` | \`${path}\` | ${layers.toSorted((a, b) => a.layer.localeCompare(b.layer)).map(({ layer, files }) => `${layer} (${String(files)})`).join(", ")} | ${dependencies.map((dependency) => `\`${dependency}\``).join(", ")} |`,
    ),
    "",
  ].join("\n")

export const renderSkills = (
  skills: ReadonlyArray<{ readonly path: string; readonly commit: string }>,
): string =>
  [
    HEADER("Pinned skills"),
    "| Skill | Commit |",
    "|---|---|",
    ...skills.map(({ path, commit }) => `| \`${path}\` | \`${commit}\` |`),
    "",
  ].join("\n")

/** Reads metric definitions out of the source that declares them, so this list cannot drift. */
export const renderInstruments = (source: string): string =>
  [
    HEADER("Metrics"),
    "Query these with `pnpm obs:metrics`. See docs/RELIABILITY.md for what each one promises.",
    "",
    "| Metric | Kind |",
    "|---|---|",
    ...[...source.matchAll(/Metric\.(timer|counter|histogram|gauge)\("([^"]+)"/g)].map(
      (match) => `| \`${match[2] ?? ""}\` | ${match[1] ?? ""} |`,
    ),
    "",
  ].join("\n")

export const renderGeneratedIndex = (): string =>
  [
    HEADER("Generated documents"),
    "- [Workspace](workspace.md): packages, their layers and dependencies.",
    "- [Pinned skills](skills.md): the commit each skill submodule is pinned to.",
    "- [Metrics](instruments.md): every metric the system records.",
    "",
  ].join("\n")
